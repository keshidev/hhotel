    public function index(Request $request)
    {
        $query = Payment::with(['booking.primaryGuest', 'booking.bookingRooms.room', 'booking.payments'])
            ->whereHas('booking'); // FIX: exclude orphaned payments (deleted booking)

        if ($request->filled('search')) {
            $search = $request->search;
            $query->where(function ($q) use ($search) {
                $q->where('transaction_reference', 'like', "%{$search}%")
                  ->orWhere('payment_method', 'like', "%{$search}%")
                  ->orWhereHas('booking', function ($bq) use ($search) {
                      $bq->where('reference_number', 'like', "%{$search}%")
                         ->orWhereHas('primaryGuest', fn ($gq) =>
                             $gq->where('name', 'like', "%{$search}%")
                         );
                  });
            });
        }

        if ($request->filled('status') && $request->status !== 'All') {
            switch ($request->status) {
                case 'Awaiting GCash':
                    $query->where('payment_status', 'pending')
                          ->where('provider', PaymentProviderService::MANUAL_GCASH);
                    break;

                case 'For Verification':
                    $query->where('payment_status', 'pending')
                          ->where(function ($q) {
                              $q->whereNull('provider');
                          });
                    break;

                case 'Accepted':
                case 'Completed':
                    $query->where('payment_status', 'completed');
                    break;

                case 'Rejected':
                case 'Failed':
                    $query->where('payment_status', 'failed');
                    break;

                case 'Pending':
                    $query->where('payment_status', 'pending');
                    break;

                default:
                    $query->where('payment_status', strtolower($request->status));
            }
        }

        if ($request->filled('method') && in_array($request->method, ['cash', 'gcash'], true)) {
            $query->where('payment_method', $request->method);
        }

        $payments = $query->latest()->get()
            ->map(fn ($payment) => $this->formatPayment($payment))
            ->filter() // FIX: remove any nulls returned by formatPayment guard
            ->values();

        return response()->json([
            'payments' => $payments,
            'stats'    => [
                'total'           => Payment::count(),
                'pending'         => Payment::where('payment_status', 'pending')->count(),
                'awaitingGcash'   => Payment::where('payment_status', 'pending')
                    ->where('provider', PaymentProviderService::MANUAL_GCASH)
                    ->count(),
                'manualPending'   => Payment::where('payment_status', 'pending')
                    ->where(function ($q) {
                        $q->whereNull('provider');
                    })->count(),
                'accepted'        => Payment::where('payment_status', 'completed')->count(),
                'rejected'        => Payment::where('payment_status', 'failed')->count(),
            ],
        ]);
    }

