    public function accept($id)
    {
        $numericId = (int) preg_replace('/[^0-9]/', '', $id);

        try {
            $payment = DB::transaction(function () use ($numericId) {
                $payment = Payment::with(['booking.primaryGuest', 'booking.bookingRooms.room', 'booking.payments'])
                    ->whereKey($numericId)
                    ->lockForUpdate()
                    ->firstOrFail();

                if ($payment->provider === 'legacy_online_gcash') {
                    throw new \RuntimeException('LEGACY_PROVIDER_READONLY');
                }

                if ($payment->provider === PaymentProviderService::MANUAL_GCASH) {
                    throw new \RuntimeException('MANUAL_GCASH_REVIEW_REQUIRED');
                }

                if ($payment->payment_status !== 'pending') {
                    throw new \RuntimeException('INVALID_PAYMENT_STATE:' . $payment->payment_status);
                }

                $payment->update([
                    'payment_status' => 'completed',
                    'verified_at'    => now(),
                    'verified_by'    => auth()->id(),
                    'paid_at'        => now(),
                ]);

                $booking = Booking::whereKey($payment->booking_id)->lockForUpdate()->first();
                if ($booking && $booking->booking_status === 'pending') {
                    $this->cancellationApprovalService->assertLifecycleUnlockedForLockedBooking(
                        booking: $booking,
                        actionCode: 'manual_payment_accept'
                    );
                    $booking->update([
                        'booking_status'     => 'confirmed',
                        'reservation_status' => 'confirmed',
                    ]);
                }

                if ($booking) {
                    $this->assignRoomToBooking($booking);
                }

                return $payment;
            });
        } catch (\RuntimeException $e) {
            if ($e->getMessage() === 'LEGACY_PROVIDER_READONLY') {
                return response()->json([
                    'success' => false,
                    'message' => 'Historical online GCash records are read-only.',
                ], 422);
            }

            if ($e->getMessage() === 'MANUAL_GCASH_REVIEW_REQUIRED') {
                return response()->json([
                    'success' => false,
                    'message' => 'Manual GCash payments must be verified through GCash Reviews.',
                ], 422);
            }

            if (str_starts_with($e->getMessage(), 'INVALID_PAYMENT_STATE:')) {
                return response()->json([
                    'success' => false,
                    'message' => 'Payment cannot be accepted. Current status: ' . substr($e->getMessage(), strlen('INVALID_PAYMENT_STATE:')),
                ], 400);
            }
            if (str_starts_with($e->getMessage(), 'BOOKING_LIFECYCLE_LOCKED:')) {
                return response()->json([
                    'success' => false,
                    'message' => 'Payment cannot be accepted while a cancellation request is in progress for this booking.',
                ], 409);
            }

            throw $e;
        }

        AuditHelper::log(
            actionActivity: 'Payment Manually Verified',
            modulePage:     'Payment Module',
            modelType:      'Payment',
            modelId:        $payment->id,
            recordAffected: 'Payment #' . $payment->id . ' - Booking ' . $payment->booking->reference_number,
            oldValues:      ['payment_status' => 'pending'],
            newValues:      [
                'payment_status' => 'completed',
                'verified_by'    => auth()->user()->name,
                'verified_at'    => now()->toDateTimeString(),
            ],
            action: 'updated'
        );

        $staffName  = auth()->user()->name ?? 'Receptionist';
        $guestName  = $payment->booking->primaryGuest->name ?? 'Guest';
        $paymentRef = 'PAY' . str_pad($payment->id, 3, '0', STR_PAD_LEFT);

