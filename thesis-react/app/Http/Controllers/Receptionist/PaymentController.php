    public function show($id)
    {
        $numericId = (int) preg_replace('/[^0-9]/', '', $id);

        $payment = Payment::with(['booking.primaryGuest', 'booking.bookingRooms.room', 'booking.payments'])
            ->findOrFail($numericId);

        $formatted = $this->formatPayment($payment);

        if ($formatted === null) {
            return response()->json(['message' => 'Payment data is incomplete or booking no longer exists.'], 422);
        }

        return response()->json($formatted);
    }

