            return;
        }

        $allowHistoricalFallback = in_array($bookingStatus, ['checked_in', 'checked_out'], true);

        $this->roomAssignmentService->assignRoomToBooking(
            booking: $booking,
            actorLabel: auth()->user()?->name ?? 'Receptionist',
            allowHistoricalFallback: $allowHistoricalFallback
        );
    }

    private function formatPayment(Payment $payment): ?array
    {
        if (!$payment->booking) {
            return null;
        }

        $bookingRooms = $payment->booking->bookingRooms->values();
        $roomLines = $bookingRooms->map(function ($bookingRoom) {
            $roomType   = $bookingRoom->room?->room_type ?? $bookingRoom->requested_room_type;
            $roomNumber = $bookingRoom->room?->room_number;

            $display = trim((string) $roomType . ' ' . (string) $roomNumber);
            if ($display === '') {
                $display = 'N/A';
            }

            return [
                'booking_room_id' => (int) $bookingRoom->id,
                'room_type'       => $roomType,
                'room_number'     => $roomNumber,
                'display'         => $display,
                'nights'          => (int) ($bookingRoom->nights ?? 0),
            ];
        });

        $roomSummary = $roomLines
            ->pluck('display')
            ->filter(fn ($display) => is_string($display) && trim($display) !== '')
            ->implode(', ');

        $allowedActions = match (true) {
            $payment->provider === PaymentProviderService::MANUAL_GCASH => 'review_only',
            $payment->provider === 'legacy_online_gcash'                => 'readonly',
            $payment->payment_status === 'pending'                      => 'manual',
            default                                                     => 'readonly',
        };

        return [
            'id'              => 'PAY' . str_pad($payment->id, 3, '0', STR_PAD_LEFT),
            'numeric_id'      => $payment->id,
            'bookingId'       => $payment->booking->reference_number,
            'guest'           => $payment->booking->primaryGuest->name ?? 'N/A',
            'amount'          => "\u{20B1}" . number_format((float) $payment->amount, 2),
            'amount_value'    => (float) $payment->amount,
            'amount_tendered_value' => round((float) ($payment->amount_tendered ?? $payment->paid_amount ?? $payment->amount), 2),
            'change_due_value' => round((float) ($payment->change_due ?? 0), 2),
            'method'          => $this->resolveDisplayMethod($payment),
            'method_key'      => (string) $payment->payment_method,
            'provider'        => $payment->provider,
            'lifecycle_status' => $payment->resolvedLifecycleStatus(),
            'lifecycle_message' => $payment->lifecycle_message,
            'reference'       => $payment->transaction_reference ?? ($payment->provider_reference ?? 'N/A'),
            'displayDate'     => ($payment->paid_at ?? $payment->created_at)?->format('Y-m-d H:i'),
            'recordedAt'      => $payment->created_at->format('Y-m-d H:i'),
            'status'          => $this->formatStatus($payment),
            'payment_status'  => $payment->payment_status,
            'proofUrl'        => $payment->proof_image
                ? asset('storage/' . $payment->proof_image)
                : null,
            'room'            => $roomSummary !== '' ? $roomSummary : 'N/A',
            'rooms'           => $roomLines->all(),
            'room_count'      => $roomLines->count(),
            'nights'          => (int) ($bookingRooms->first()?->nights ?? 0),
            'allowed_actions' => $allowedActions,
            'paid_at'         => $payment->paid_at?->format('Y-m-d H:i'),
            'notes'           => $payment->notes,
        ];
    }

    private function resolveDisplayMethod(Payment $payment): string{
        $methodKey = strtolower(trim((string) $payment->payment_method));

        if ($methodKey !== 'original_payment_method') {
            return $this->formatMethodLabel($methodKey);
        }

        $bookingPayments = $payment->booking?->payments ?? collect();

        $sourcePayment = $bookingPayments
            ->filter(function ($row) use ($payment) {
                return (int) $row->id !== (int) $payment->id
                    && strtolower((string) $row->payment_type) !== 'refund'
                    && strtolower((string) $row->payment_status) === 'completed';
            })
            ->sortByDesc(function ($row) {
                return optional($row->paid_at ?? $row->created_at)->getTimestamp() ?? 0;
            })
            ->first();

        if (!$sourcePayment) {
            return 'Original payment method';
        }

        return $this->formatMethodLabel((string) $sourcePayment->payment_method);
    }

    private function formatMethodLabel(string $method): string
    {
        $key = strtolower(trim($method));

        return match ($key) {
            'gcash' => 'GCash',
            'paymaya' => 'PayMaya',
            'credit_card' => 'Credit Card',
            'bank_transfer' => 'Bank Transfer',
            default => ucfirst(str_replace('_', ' ', $key)),
        };
    }

    private function formatStatus(Payment $payment): string
    {
        $lifecycleLabel = match ($payment->resolvedLifecycleStatus()) {
            Payment::LIFECYCLE_AUTHORIZED => 'Authorized - Awaiting Capture',
            Payment::LIFECYCLE_CAPTURE_PENDING => 'Capture Pending',
            Payment::LIFECYCLE_CAPTURE_UNKNOWN => 'Capture Status Unknown',
            Payment::LIFECYCLE_PAID_UNDER_REVIEW => 'Paid - Under Review',
            Payment::LIFECYCLE_REFUND_REQUIRED => 'Paid - Refund Required',
            Payment::LIFECYCLE_ASSIGNMENT_FAILED => 'Paid - Assignment Required',
            default => null,
        };

        if ($lifecycleLabel !== null) {
            return $lifecycleLabel;
        }

        return match ($payment->payment_status) {
            'pending'   => 'Pending',
            'completed' => 'Accepted',
            'failed'    => 'Rejected',
            'refunded'  => 'Refunded',
            default     => ucfirst($payment->payment_status),
        };
    }
